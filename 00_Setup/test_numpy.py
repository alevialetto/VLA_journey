import numpy as np

# Creiamo un array
array_semplice = np.array([1, 2, 3, 4, 5])
print("Il mio primo array:", array_semplice)

# Facciamo un'operazione matematica
array_moltiplicato = array_semplice * 2
print("Array moltiplicato per 2:", array_moltiplicato)

# Calcoliamo la media
print("La media è:", np.mean(array_semplice))